-- Apply in Supabase SQL Editor as the project owner. Records contain fictional demo data.
create table if not exists profiles (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  role text not null default 'viewer' check (role in ('admin','analyst','viewer')),
  created_at timestamptz not null default now()
);
create table if not exists aircraft (
  id bigint generated by default as identity primary key,
  resource_id text not null unique,
  category text not null,
  availability_status text not null,
  maintenance_status text not null,
  readiness_confirmation boolean not null default false,
  notes text not null default '',
  updated_at timestamptz not null default now()
);
create table if not exists crew (
  id bigint generated by default as identity primary key,
  display_id text not null unique,
  group_name text not null,
  readiness_status text not null,
  confirmation_at timestamptz
);
create table if not exists maintenance_records (
  id bigint generated by default as identity primary key,
  aircraft_id bigint references aircraft(id) on delete set null,
  title text not null,
  status text not null,
  priority text not null default 'normal',
  due_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists weather_observations (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null,
  location text not null,
  temperature_c double precision,
  humidity_pct double precision check (humidity_pct between 0 and 100),
  wind_kmh double precision,
  precipitation_mm double precision,
  source text not null default 'demo'
);
create table if not exists schedule_records (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  status text not null,
  starts_at timestamptz not null,
  ends_at timestamptz
);
create table if not exists alerts (
  id bigint generated by default as identity primary key,
  severity text not null check (severity in ('low','medium','high','critical')),
  category text not null,
  message text not null,
  status text not null default 'open' check (status in ('open','acknowledged','resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create table if not exists analysis_reports (
  id bigint generated by default as identity primary key,
  report_type text not null,
  filters_json text not null default '{}',
  summary text not null,
  generated_by bigint references profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists audit_logs (
  id bigint generated by default as identity primary key,
  profile_id bigint references profiles(id) on delete set null,
  action text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists ix_maintenance_aircraft_id on maintenance_records(aircraft_id);
create index if not exists ix_maintenance_status on maintenance_records(status);
create index if not exists ix_weather_observed_at on weather_observations(observed_at);
create index if not exists ix_schedule_starts_status on schedule_records(starts_at,status);
create index if not exists ix_alerts_status_severity on alerts(status,severity);
create index if not exists ix_alerts_created_at on alerts(created_at);
create index if not exists ix_analysis_created_at on analysis_reports(created_at);
create index if not exists ix_audit_created_at on audit_logs(created_at);

