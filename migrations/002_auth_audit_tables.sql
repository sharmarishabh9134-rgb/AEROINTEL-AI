-- Add the two app support tables without altering the existing operational tables.
-- First run `python -m scripts.inspect_database` and review the actual Supabase schema.
-- Apply only if these tables are absent and their names are not already used differently.
create table if not exists profiles (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  role text not null default 'viewer' check (role in ('admin','analyst','viewer')),
  created_at timestamptz not null default now()
);

create table if not exists audit_logs (
  id bigint generated by default as identity primary key,
  profile_id bigint references profiles(id) on delete set null,
  action text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists ix_audit_created_at on audit_logs(created_at);

-- Nullable ownership preserves existing report rows. Apply only after confirming
-- the existing analysis_reports table and column layout with the inspector.
alter table if exists analysis_reports
  add column if not exists generated_by bigint references profiles(id) on delete set null;

alter table profiles enable row level security;
alter table audit_logs enable row level security;

