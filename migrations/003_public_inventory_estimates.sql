-- Additive table for versioned public inventory estimates. Does not alter
-- operational aircraft/readiness tables or existing rows.
create table if not exists public_inventory_records (
  id bigint generated by default as identity primary key,
  record_key varchar(120) not null unique,
  organization varchar(80) not null,
  display_name varchar(140) not null,
  category varchar(60) not null,
  estimated_count integer not null check (estimated_count > 0),
  count_type varchar(40) not null check (count_type in ('estimated_inventory','procurement_order')),
  country varchar(80) not null default 'India',
  role varchar(120) not null,
  source_name varchar(160) not null,
  source_url varchar(500) not null,
  source_date timestamptz not null,
  last_imported_at timestamptz not null default now(),
  verification_status varchar(60) not null default 'unverified_open_source_estimate',
  data_classification varchar(40) not null default 'ESTIMATE' check (data_classification in ('PUBLIC_REFERENCE','ESTIMATE','SIMULATED')),
  is_active_inventory boolean not null default true,
  dataset_version varchar(40) not null
);
create index if not exists ix_public_inventory_org_category on public_inventory_records(organization, category);
create index if not exists ix_public_inventory_version on public_inventory_records(dataset_version);
create index if not exists ix_public_inventory_active on public_inventory_records(is_active_inventory);

-- If RLS is enabled on this Supabase table, authorize only the dedicated backend
-- database login. The browser reads public inventory through the API, not PostgREST.
alter table public_inventory_records enable row level security;
